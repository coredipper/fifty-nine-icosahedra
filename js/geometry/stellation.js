// Stellations of the icosahedron.
//
// The 20 face planes of the regular icosahedron divide space into cells.
// Cells related by a symmetry of the icosahedron form one cell type; cell
// types at the same "depth" (number of face planes a cell lies outside of)
// form a shell, named a, b, c, ... h working outwards (Coxeter et al.,
// "The Fifty-Nine Icosahedra", 1938). A stellation is a union of cell types.
//
// Its surface lies in the 20 face planes. In one plane the other planes cut
// lines that form the stellation diagram; a region of the diagram is part of
// the surface when the cell on one side belongs to the stellation and the
// cell on the other side does not. One plane is computed and copied to the
// other 19 by rotations.

import { add, cross, dot, length, matMul, matVec, normalize, reflection, scale, sub, IDENTITY, determinant } from './vec.js';

const PHI = (1 + Math.sqrt(5)) / 2;
const EPS = 1e-9;

// Regular icosahedron with vertices (0, +-1, +-phi) and cyclic shifts
// (edge 2). Its face normals point at the dodecahedron vertices
// (+-1, +-1, +-1) and cyclic shifts of (0, +-phi, +-1/phi).
const INRADIUS = (PHI * PHI) / Math.sqrt(3);

function faceNormals() {
  const normals = [];
  for (const x of [-1, 1]) for (const y of [-1, 1]) for (const z of [-1, 1]) normals.push([x, y, z]);
  for (const a of [-PHI, PHI]) {
    for (const b of [-1 / PHI, 1 / PHI]) {
      normals.push([0, a, b], [a, b, 0], [b, 0, a]);
    }
  }
  return normals.map(normalize);
}

export const NORMALS = faceNormals();
const PLANE_DISTANCE = INRADIUS;

function sameMatrix(a, b) {
  return a.every((x, i) => Math.abs(x - b[i]) < 1e-9);
}

/** The 120 symmetries of the icosahedron, generated by four of its mirrors. */
export const GROUP = (() => {
  const mirrors = [[1, 0, 0], [0, 1, 0], [0, 0, 1], normalize([1 - PHI, PHI, -1])].map(reflection);
  const elements = [IDENTITY];
  for (let i = 0; i < elements.length; i++) {
    for (const g of mirrors) {
      const m = matMul(g, elements[i]);
      if (!elements.some((e) => sameMatrix(e, m))) elements.push(m);
      if (elements.length > 120) throw new Error('Mirrors do not generate the icosahedral group');
    }
  }
  return elements;
})();

export const ROTATIONS = GROUP.filter((g) => determinant(g) > 0);

const planeIndex = (n) => NORMALS.findIndex((m) => length(sub(m, n)) < 1e-9);

/** For each group element, where it sends each face plane. */
const PERMUTATIONS = GROUP.map((g) => NORMALS.map((n) => planeIndex(matVec(g, n))));
const ROTATION_PERMUTATIONS = PERMUTATIONS.filter((_, k) => determinant(GROUP[k]) > 0);

/** +1 where the point is outside a face plane, -1 where inside. */
function signVector(x) {
  return NORMALS.map((n) => (dot(n, x) > PLANE_DISTANCE ? 1 : -1));
}

/** Smallest image of a sign vector under a set of plane permutations. */
function canonical(signs, permutations) {
  let best = null;
  for (const perm of permutations) {
    const image = new Array(20);
    for (let i = 0; i < 20; i++) image[perm[i]] = signs[i] > 0 ? '1' : '0';
    const key = image.join('');
    if (best === null || key < best) best = key;
  }
  return best;
}

/** A cell is bounded when no direction keeps it on the same side of every plane. */
function isBounded(signs) {
  for (let i = 0; i < 20; i++) {
    for (let j = i + 1; j < 20; j++) {
      const c = cross(NORMALS[i], NORMALS[j]);
      if (length(c) < 1e-9) continue;
      for (const u of [c, scale(c, -1)]) {
        if (NORMALS.every((n, k) => signs[k] * dot(n, u) >= -1e-9)) return false;
      }
    }
  }
  return true;
}

const cellCache = new Map();

/**
 * Cell containing a point: { bounded, depth, type, half }. `type` is the
 * orbit under all 120 symmetries, `half` the orbit under the 60 rotations
 * (cell types that are not mirror symmetric split into two halves).
 */
function cellAt(x) {
  const signs = signVector(x);
  const key = signs.join(',');
  if (!cellCache.has(key)) {
    const bounded = isBounded(signs);
    cellCache.set(key, {
      bounded,
      depth: signs.filter((s) => s > 0).length,
      type: bounded ? canonical(signs, PERMUTATIONS) : null,
      half: bounded ? canonical(signs, ROTATION_PERMUTATIONS) : null,
    });
  }
  return cellCache.get(key);
}

// ---------------------------------------------------------------------------
// The stellation diagram in face plane 0.

const N0 = NORMALS[0];
const ORIGIN = scale(N0, PLANE_DISTANCE);
const U = normalize(cross(N0, Math.abs(N0[0]) < 0.9 ? [1, 0, 0] : [0, 1, 0]));
const W = cross(N0, U);
export const to3D = (q) => add(ORIGIN, add(scale(U, q[0]), scale(W, q[1])));

/** Split a convex polygon by the line A a + B b = C. */
function splitPolygon(poly, [A, B, C]) {
  const side = (p) => A * p[0] + B * p[1] - C;
  const left = [];
  const right = [];
  for (let i = 0; i < poly.length; i++) {
    const p = poly[i];
    const q = poly[(i + 1) % poly.length];
    const sp = side(p);
    const sq = side(q);
    if (sp <= EPS) left.push(p);
    if (sp >= -EPS) right.push(p);
    if ((sp < -EPS && sq > EPS) || (sp > EPS && sq < -EPS)) {
      const t = sp / (sp - sq);
      const r = [p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t];
      left.push(r);
      right.push(r);
    }
  }
  const area = (P) => P.length < 3 ? 0 : Math.abs(P.reduce((s, p, i) => {
    const q = P[(i + 1) % P.length];
    return s + p[0] * q[1] - q[0] * p[1];
  }, 0)) / 2;
  return [left, right].map(cleanPolygon).filter((P) => area(P) > 1e-12);
}

/** Remove repeated and collinear vertices left by clipping. */
function cleanPolygon(poly) {
  let points = poly.filter((p, i) => Math.hypot(p[0] - poly[(i + 1) % poly.length][0], p[1] - poly[(i + 1) % poly.length][1]) > 1e-9);
  let changed = true;
  while (changed && points.length > 3) {
    changed = false;
    for (let i = 0; i < points.length; i++) {
      const a = points[(i + points.length - 1) % points.length];
      const b = points[i];
      const c = points[(i + 1) % points.length];
      if (Math.abs((b[0] - a[0]) * (c[1] - b[1]) - (b[1] - a[1]) * (c[0] - b[0])) < 1e-9) {
        points = points.filter((_, k) => k !== i);
        changed = true;
        break;
      }
    }
  }
  return points;
}

/** Area centroid of a convex polygon. */
function areaCentroid(poly) {
  let a = 0;
  let cx = 0;
  let cy = 0;
  poly.forEach((p, i) => {
    const q = poly[(i + 1) % poly.length];
    const w = p[0] * q[1] - q[0] * p[1];
    a += w;
    cx += (p[0] + q[0]) * w;
    cy += (p[1] + q[1]) * w;
  });
  return [cx / (3 * a), cy / (3 * a)];
}

const BOX = 1000;

/** Bounded regions of the stellation diagram (convex polygons, 2D). */
export const DIAGRAM = (() => {
  const lines = [];
  for (let j = 1; j < 20; j++) {
    const n = NORMALS[j];
    const A = dot(n, U);
    const B = dot(n, W);
    if (Math.hypot(A, B) < 1e-9) continue; // the opposite, parallel face
    lines.push([A, B, PLANE_DISTANCE - dot(n, ORIGIN)]);
  }
  let regions = [[[-BOX, -BOX], [BOX, -BOX], [BOX, BOX], [-BOX, BOX]]];
  for (const line of lines) regions = regions.flatMap((poly) => splitPolygon(poly, line));
  const bounded = regions.filter((poly) => poly.every((p) => Math.abs(p[0]) < BOX / 2 && Math.abs(p[1]) < BOX / 2));
  return bounded.map((polygon) => {
    const c = areaCentroid(polygon);
    const centre = to3D(c);
    return {
      polygon,
      centre2D: c,
      outside: cellAt(add(centre, scale(N0, 1e-6))),
      inside: cellAt(add(centre, scale(N0, -1e-6))),
    };
  });
})();

// ---------------------------------------------------------------------------
// Cell types and shells.

/**
 * Signed twist of a rotation half around the outward face normal N0 relative
 * to the core icosahedron triangle: positive for the counter-clockwise
 * (right-hand rule around +N0) enantiomorph, negative for its mirror image.
 * Ordering chiral halves by this twist makes enantiomorph selection geometric
 * rather than dependent on the enumeration order of NORMALS.
 */
function halfTwist(half) {
  const icoVertices = DIAGRAM.find((r) => r.inside.depth === 0).polygon;
  let total = 0;
  for (const r of DIAGRAM) {
    if (r.inside.half !== half) continue;
    const c = r.centre2D;
    let nearest = icoVertices[0];
    let bestDot = -Infinity;
    for (const v of icoVertices) {
      const d = v[0] * c[0] + v[1] * c[1];
      if (d > bestDot) {
        bestDot = d;
        nearest = v;
      }
    }
    total += nearest[0] * c[1] - nearest[1] * c[0];
  }
  return total;
}

/**
 * All bounded cell types, sorted by depth. Each has { type, depth, halves }:
 * the rotation orbits it splits into (one for mirror-symmetric types, two
 * otherwise, ordered by geometric twist so halves[0] is positive / CCW around
 * the outward face normal and halves[1] is its mirror image).
 */
export const CELL_TYPES = (() => {
  const types = new Map();
  for (const region of DIAGRAM) {
    for (const cell of [region.inside, region.outside]) {
      if (!cell.bounded) continue;
      if (!types.has(cell.type)) types.set(cell.type, { type: cell.type, depth: cell.depth, halves: new Set() });
      types.get(cell.type).halves.add(cell.half);
    }
  }
  return [...types.values()]
    .map((t) => {
      const halves = [...t.halves];
      if (halves.length === 2) halves.sort((a, b) => halfTwist(b) - halfTwist(a));
      return { ...t, halves };
    })
    .sort((a, b) => a.depth - b.depth || (a.type < b.type ? -1 : 1));
})();

/** One cell of each type as a rough size measure: number of diagram regions it touches. */
export function shells() {
  const byDepth = new Map();
  for (const t of CELL_TYPES) {
    if (!byDepth.has(t.depth)) byDepth.set(t.depth, []);
    byDepth.get(t.depth).push(t);
  }
  return [...byDepth.entries()].sort((a, b) => a[0] - b[0]).map(([depth, types]) => ({ depth, types }));
}

/** Rotation that maps face plane 0 to face plane j, for each j. */
export const PLANE_ROTATIONS = NORMALS.map((n) => ROTATIONS.find((g) => length(sub(matVec(g, N0), n)) < 1e-9));

/** Stabiliser of plane 0 in the full group (order 6), for region types. */
export const PLANE_STABILISER = GROUP.filter((g) => length(sub(matVec(g, N0), N0)) < 1e-9);

// ---------------------------------------------------------------------------
// Coxeter's cell names.

/**
 * Map from Coxeter cell name to cell type. Shells with two types: f1 is the
 * chiral one (its two rotation halves are the enantiomorphs written f1 and
 * italic f1). For e and g, `order` picks which type is called 1; the tests
 * fix it by matching the face sets listed on Wikipedia for all 59.
 */
export function cellNames(order = { e: 0, g: 0 }) {
  const byDepth = shells();
  const names = {};
  const letters = 'abcdefgh';
  byDepth.forEach(({ types }, depth) => {
    const letter = letters[depth];
    if (types.length === 1) {
      names[letter] = types[0];
    } else if (letter === 'f') {
      const chiral = types.find((t) => t.halves.length === 2);
      names.f1 = chiral;
      names.f2 = types.find((t) => t !== chiral);
    } else {
      const first = order[letter] ?? 0;
      names[`${letter}1`] = types[first];
      names[`${letter}2`] = types[1 - first];
    }
  });
  return names;
}

const CELL_NAMES = cellNames({ e: 0, g: 0 });

/**
 * Parse Coxeter's notation into the set of cells it contains. A capital
 * letter means every shell up to and including it ("D" = a, b, c, d);
 * lower-case names add single cell types. `chiralF1` selects one rotation
 * half of f1 (the italic f1 of the chiral stellations); `mirror` switches to
 * the opposite enantiomorph.
 */
export function parseCells(notation, { chiralF1 = false, mirror = false, names = CELL_NAMES } = {}) {
  const types = new Set();
  const halves = new Set();
  const tokens = typeof notation === 'string' ? (notation.match(/[A-H]|[a-h][12]?/g) ?? []) : [];
  if (!notation || tokens.join('') !== notation) throw new Error(`Cannot parse cell notation "${notation}"`);
  const shellNames = { a: ['a'], b: ['b'], c: ['c'], d: ['d'], e: ['e1', 'e2'], f: ['f1', 'f2'], g: ['g1', 'g2'], h: ['h'] };
  for (const token of tokens) {
    if (/[A-H]/.test(token)) {
      for (const letter of 'abcdefgh'.slice(0, 'ABCDEFGH'.indexOf(token) + 1)) {
        for (const name of shellNames[letter]) types.add(names[name].type);
      }
    } else if (token === 'f1' && chiralF1) {
      halves.add(names.f1.halves[mirror ? 1 : 0]);
    } else {
      if (!names[token]) throw new Error(`Unknown cell "${token}"`);
      types.add(names[token].type);
    }
  }
  return { types, halves };
}

const inSet = (cell, set) => cell.bounded && (set.types.has(cell.type) || set.halves.has(cell.half));

/**
 * Diagram regions of plane 0 that belong to the surface of a cell set.
 * Each region includes `outward`: true when the solid is on the inside (-N0)
 * side so the outward normal is +N0, false for underside (') faces whose
 * outward normal is -N0.
 */
export function surfaceRegions(set) {
  const regions = [];
  for (const r of DIAGRAM) {
    const inside = inSet(r.inside, set);
    const outside = inSet(r.outside, set);
    if (inside !== outside) regions.push({ ...r, outward: inside });
  }
  return regions;
}

const formatCoord = (x) => (Math.abs(x) < 1e-9 ? 0 : x).toFixed(6);

/** Type of a diagram region under the symmetries of its plane (for the face sets). */
export function regionType(region) {
  const c = to3D(region.centre2D);
  let best = null;
  for (const g of PLANE_STABILISER) {
    const key = matVec(g, c).map(formatCoord).join(',');
    if (best === null || key < best) best = key;
  }
  return best;
}
